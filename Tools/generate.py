#!/usr/bin/env python3
"""Generate the two build-time headers of AW88399Fixup.

1. Sources/AW88399Fixup/AW88399Registers.hpp
      Derived from the vendored Linux reference header
      Sources/AW88399Fixup/Registers/reference/linux-aw88399.h
      (include/sound/aw88399.h from the mainline Linux kernel, GPL-2.0-only).
      The #define lines are copied verbatim so the preprocessor handles the
      ordering and the complement-mask convention exactly like Linux does.

2. Sources/AW88399Fixup/Firmware/aw88399_acf.h
      The ACF/DSP configuration blob as a C array (used from milestone M2 on).

Both outputs are build products and are listed in .gitignore.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "Sources" / "AW88399Fixup"
REFERENCE = SRC / "Registers" / "reference" / "linux-aw88399.h"
REG_OUT = SRC / "AW88399Registers.hpp"
ACF_IN = SRC / "Firmware" / "aw88399_acf.bin"
ACF_OUT = SRC / "Firmware" / "aw88399_acf.h"

BANNER = "// Generated by Tools/generate.py - do not edit, do not commit."


def parse_defines(text: str) -> list[tuple[str, str]]:
    """Return (name, body) for every #define in the reference header."""
    defines: list[tuple[str, str]] = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("#define"):
            body = line
            while body.rstrip().endswith("\\") and i + 1 < len(lines):
                i += 1
                body = body.rstrip()[:-1] + lines[i]
            match = re.match(r"#define\s+([A-Za-z_][A-Za-z0-9_]*)\s*(.*)$", body, re.S)
            if match:
                defines.append((match.group(1), match.group(2).strip()))
        i += 1
    return defines


def generate_registers() -> int:
    text = REFERENCE.read_text(encoding="utf-8")
    defines = parse_defines(text)
    if not defines:
        raise SystemExit("no #define found in %s" % REFERENCE)

    out = [
        BANNER,
        "//",
        "// Register/bit definitions for the Awinic AW88399, taken from the Linux kernel",
        "// reference header (see docs/references.md). The mask constants are, as in",
        "// Linux, the *complement* of the corresponding field mask.",
        "",
        "#ifndef AW88399_REGISTERS_HPP",
        "#define AW88399_REGISTERS_HPP",
        "",
        "#include <IOKit/IOTypes.h>",
        "",
    ]
    for name, body in defines:
        out.append("#define %s %s" % (name, body))
    out += ["", "#endif /* AW88399_REGISTERS_HPP */", ""]

    REG_OUT.write_text("\n".join(out), encoding="utf-8")
    return len(defines)


def generate_firmware() -> tuple[int, str]:
    blob = ACF_IN.read_bytes()
    digest = hashlib.sha256(blob).hexdigest()

    lines = [
        BANNER,
        "//",
        "// Awinic AW88399 ACF/DSP configuration blob (aw88399_acf.bin).",
        "// sha256: %s" % digest,
        "// Used from milestone M2 on; M1 runs the amplifier in DSP bypass mode.",
        "",
        "#ifndef AW88399_ACF_FIRMWARE_H",
        "#define AW88399_ACF_FIRMWARE_H",
        "",
        "static const unsigned int kAW88399AcfFirmwareLength = %d;" % len(blob),
        "static const unsigned char kAW88399AcfFirmware[] = {",
    ]
    for offset in range(0, len(blob), 16):
        chunk = blob[offset:offset + 16]
        lines.append("    " + " ".join("0x%02x," % byte for byte in chunk))
    lines += ["};", "", "#endif /* AW88399_ACF_FIRMWARE_H */", ""]

    ACF_OUT.write_text("\n".join(lines), encoding="utf-8")
    return len(blob), digest


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if not REFERENCE.exists():
        raise SystemExit("missing reference header: %s" % REFERENCE)
    if not ACF_IN.exists():
        raise SystemExit("missing firmware blob: %s" % ACF_IN)

    count = generate_registers()
    length, digest = generate_firmware()
    print("registers : %-40s (%d defines)" % (REG_OUT.relative_to(ROOT), count))
    print("firmware  : %-40s (%d bytes)" % (ACF_OUT.relative_to(ROOT), length))
    print("acf sha256: %s" % digest)


if __name__ == "__main__":
    main()
